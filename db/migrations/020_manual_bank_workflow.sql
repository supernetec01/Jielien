-- Additive only: existing order/payment snapshots are left untouched.
ALTER TABLE orders ADD COLUMN bank_payment_due_at TIMESTAMPTZ;
ALTER TABLE orders ADD COLUMN bank_payment_reported_at TIMESTAMPTZ;
CREATE TABLE staff_notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_key TEXT NOT NULL UNIQUE,
  kind TEXT NOT NULL CHECK(kind IN ('bank_order','customer_transfer_notice')),
  order_id BIGINT NOT NULL REFERENCES orders(id),
  amount BIGINT NOT NULL CHECK(amount>=0),
  status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed')),
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  sent_at TIMESTAMPTZ
);
CREATE INDEX staff_notifications_pending_idx ON staff_notifications(next_attempt_at,id) WHERE status='pending';
CREATE INDEX orders_bank_expiry_idx ON orders(created_at,id) WHERE payment_method='bank_transfer' AND status IN ('pending','confirmed','processing');
